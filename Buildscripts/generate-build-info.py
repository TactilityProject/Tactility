#!/usr/bin/env python3
"""
Writes the identity of the build: the git commit and the build time.

Usage: generate-build-info.py <repository-folder> <version-file> <c-output-folder> <json-output-path>

Writes build_info.c to the C output folder and a JSON file with the same values, which the CDN files are made from.
The build time is kept while the commit stays the same, so incremental builds of a commit don't recompile.
The release channel comes from the TT_BUILD_CHANNEL environment variable: stable, unstable or develop (the default).
"""
import json
import os
import subprocess
import sys
import time

CHANNELS = ["stable", "unstable", "develop"]


def read_git_commit(repository_folder: str) -> str:
    try:
        return subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=repository_folder, stderr=subprocess.DEVNULL).decode("ascii").strip()
    except (OSError, subprocess.CalledProcessError):
        return ""


def read_previous(json_path: str):
    try:
        with open(json_path, "r", encoding="utf-8") as file:
            return json.load(file)
    except (OSError, ValueError):
        return None


def write_if_changed(path: str, content: str):
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8", newline="") as file:
            if file.read() == content:
                return
    with open(path, "w", encoding="utf-8", newline="") as file:
        file.write(content)


def main():
    if len(sys.argv) != 5:
        print(f"Usage: {sys.argv[0]} <repository-folder> <version-file> <c-output-folder> <json-output-path>")
        sys.exit(1)
    repository_folder, version_file, c_output_folder, json_path = sys.argv[1:]
    with open(version_file, "r", encoding="utf-8") as file:
        version = file.read().strip()
    channel = os.environ.get("TT_BUILD_CHANNEL", "develop") or "develop"
    if channel not in CHANNELS:
        print(f"Invalid TT_BUILD_CHANNEL: {channel}, expected one of {CHANNELS}")
        sys.exit(1)
    git_commit = read_git_commit(repository_folder)
    previous = read_previous(json_path)
    if previous is not None and previous.get("gitCommit") == git_commit and previous.get("version") == version and isinstance(previous.get("created"), int):
        created = previous["created"]
    else:
        created = int(time.time())
    info = {"version": version, "gitCommit": git_commit, "created": created, "channel": channel}
    write_if_changed(json_path, json.dumps(info, indent=2) + "\n")
    c_source = (
        "// Generated by Buildscripts/generate-build-info.py\n"
        f"const char tt_build_git_commit[] = \"{git_commit}\";\n"
        f"const long long tt_build_timestamp = {created}LL;\n"
        f"const char tt_build_channel[] = \"{channel}\";\n"
    )
    write_if_changed(os.path.join(c_output_folder, "build_info.c"), c_source)


if __name__ == "__main__":
    main()
