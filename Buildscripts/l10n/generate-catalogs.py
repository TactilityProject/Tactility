#!/usr/bin/env python3
"""
Compiles the PO files of the translation folders into binary catalogs and embeds them as C byte arrays.

Usage: generate-catalogs.py <translations-folder> <output-folder>

Each subfolder of the translations folder is a domain: "tactility" holds the system catalogs and the others belong to
an app. A file "nl-NL.po" is the catalog for the locale "nl-NL". Writes generated_catalogs.c and generated_catalogs.h
with a table of the domain, locale and data of every catalog.
Output files are only rewritten when their content changes, to avoid needless recompiles.
"""
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "TactilitySDK", "Tools"))
from po2tlc import build_catalog, parse_po  # noqa: E402


def write_if_changed(path: str, content: str):
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8", newline="") as file:
            if file.read() == content:
                return
    with open(path, "w", encoding="utf-8", newline="") as file:
        file.write(content)


def main():
    if len(sys.argv) != 3:
        print(f"Usage: {sys.argv[0]} <po-folder> <output-folder>")
        sys.exit(1)
    translations_folder, output_folder = sys.argv[1], sys.argv[2]
    os.makedirs(output_folder, exist_ok=True)

    catalogs = []
    if os.path.isdir(translations_folder):
        for domain in sorted(os.listdir(translations_folder)):
            po_folder = os.path.join(translations_folder, domain)
            if not os.path.isdir(po_folder):
                continue
            for file_name in sorted(os.listdir(po_folder)):
                if file_name.endswith(".po"):
                    locale = file_name[:-3]
                    if not re.fullmatch(r"[A-Za-z0-9_-]{1,15}", locale):
                        print(f"Invalid locale in file name: {domain}/{file_name}")
                        sys.exit(1)
                    catalogs.append((domain, locale, build_catalog(parse_po(os.path.join(po_folder, file_name)))))

    header = [
        "// Generated by Buildscripts/l10n/generate-catalogs.py. Do not edit.",
        "#pragma once",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
        "/** A translation catalog that is part of the firmware */",
        "struct GeneratedCatalog {",
        "    const char* domain;",
        "    const char* locale;",
        "    const uint8_t* data;",
        "    size_t size;",
        "};",
        "",
        "extern const struct GeneratedCatalog generated_catalogs[];",
        "extern const size_t generated_catalogs_count;",
        "",
        "#ifdef __cplusplus",
        "}",
        "#endif",
        "",
    ]
    source = ["// Generated by Buildscripts/l10n/generate-catalogs.py. Do not edit.", '#include "generated_catalogs.h"', ""]
    for index, (domain, locale, data) in enumerate(catalogs):
        source.append(f"static const uint8_t catalog_{index}[] = {{")
        for offset in range(0, len(data), 24):
            source.append("    " + ", ".join(f"0x{byte:02x}" for byte in data[offset:offset + 24]) + ",")
        source.append("};")
    source.append("")
    source.append("const struct GeneratedCatalog generated_catalogs[] = {")
    for index, (domain, locale, data) in enumerate(catalogs):
        source.append(f'    {{ "{domain}", "{locale}", catalog_{index}, {len(data)} }},')
    if not catalogs:
        source.append("    { 0, 0, 0, 0 }")
    source.append("};")
    source.append(f"const size_t generated_catalogs_count = {len(catalogs)};")
    source.append("")

    write_if_changed(os.path.join(output_folder, "generated_catalogs.h"), "\n".join(header))
    write_if_changed(os.path.join(output_folder, "generated_catalogs.c"), "\n".join(source))


if __name__ == "__main__":
    main()
